// Bundles each edge function into one self-contained file, so it can be
// deployed from the Supabase dashboard (which uploads only the function's
// own file) as well as with the CLI.
//
//   source:  supabase/edge-src/<name>.ts   (may import supabase/functions/_shared/*)
//   output:  supabase/functions/<name>/index.ts   ← deploy this
//
// Run: npm run build:edge

import { build } from 'esbuild';
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'fs';
import { join, basename } from 'path';

const SRC = 'supabase/edge-src';
const OUT = 'supabase/functions';

for (const file of readdirSync(SRC).filter(f => f.endsWith('.ts'))) {
  const name = basename(file, '.ts');
  const result = await build({
    entryPoints: [join(SRC, file)],
    bundle: true,
    format: 'esm',
    platform: 'neutral',
    target: 'es2022',
    write: false,
    // Remote imports are fetched by Deno at deploy time.
    external: ['https://*', 'npm:*', 'jsr:*'],
    legalComments: 'none',
  });
  const header = `// GENERATED by scripts/build-edge.mjs from ${SRC}/${file} — do not edit here.\n`
    + `// Edit the source, then run \`npm run build:edge\` and deploy this file.\n\n`;
  mkdirSync(join(OUT, name), { recursive: true });
  const target = join(OUT, name, 'index.ts');
  const code = header + result.outputFiles[0].text;
  let previous = '';
  try { previous = readFileSync(target, 'utf8'); } catch { /* new function */ }
  writeFileSync(target, code);
  console.log(`${previous === code ? 'unchanged' : 'built'} ${target} (${(code.length / 1024).toFixed(1)} KB)`);
}
